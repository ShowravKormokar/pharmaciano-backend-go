// CreateProductCategory inserts a category.
//
// SortOrder and IsActive are resolved before the call because CreateProductCategory
// writes every non-generated column: an unresolved nil would store 0/false rather
// than the schema defaults 0/TRUE (§28.5). SortOrder's default happens to equal its
// zero value, but it is resolved through intOr anyway so the intent is explicit and
// the two stay correct if a default ever changes.
//
// When a parent is supplied the operation is genuinely two statements — prove the
// parent is live, then insert — so it runs in a transaction (contract §15). A root
// category needs only the INSERT.
//
// Self-reference is impossible on create: the id is generated by the database, so
// there is nothing for parent_id to point at yet. It is still rejected on update,
// and in both directions by ck_product_categories_parent_not_self (000020).
func (s *Service) CreateProductCategory(ctx context.Context, req *CreateProductCategoryRequest) (*ProductCategory, error) {
	if err := s.requireSuperAdmin(ctx); err != nil {
		return nil, err
	}
	c := &ProductCategory{
		Code:        req.Code,
		Name:        req.Name,
		ParentID:    req.ParentID,
		Description: req.Description,
		SortOrder:   intOr(req.SortOrder, 0),
		IsActive:    boolOr(req.IsActive, true),
	}
	if req.ParentID == nil {
		return s.insertProductCategory(ctx, c)
	}

	var out *ProductCategory
	err := s.db.WithTx(ctx, func(ctx context.Context) error {
		if err := requireReference(ctx, req.ParentID, s.repo.GetProductCategory, resProductCategory); err != nil {
			return err
		}
		created, err := s.repo.CreateProductCategory(ctx, c)
		if err != nil {
			return mapWriteErr(err, resProductCategory)
		}
		out = created
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}

// insertProductCategory is the single-statement create path, shared by the root case
// above so the insert and its error mapping are written once.
func (s *Service) insertProductCategory(ctx context.Context, c *ProductCategory) (*ProductCategory, error) {
	created, err := s.repo.CreateProductCategory(ctx, c)
	if err != nil {
		return nil, mapWriteErr(err, resProductCategory)
	}
	return created, nil
}

// GetProductCategory returns one live category, or NotFound.
func (s *Service) GetProductCategory(ctx context.Context, id uuid.UUID) (*ProductCategory, error) {
	c, err := s.repo.GetProductCategory(ctx, id)
	if err != nil {
		return nil, mapReadErr(err, resProductCategory)
	}
	return c, nil
}

// ListProductCategories returns a filtered, paginated page of categories plus meta.
// This is one of the three resources whose ?parent_id= filter is honoured.
func (s *Service) ListProductCategories(ctx context.Context, q *ListMasterDataQuery) ([]ProductCategory, pagination.Meta, error) {
	return listPage(ctx, q, s.repo.ListProductCategories)
}

// UpdateProductCategory applies a partial change, including a re-parent.
//
// The whole thing runs in one transaction under a row lock: the new parent is proved
// to be live and the row is rewritten together, so a re-parent cannot be observed
// half-applied and cannot race a concurrent update (contract §15).
//
// An empty PATCH degrades to a read; code is immutable and not patchable.
func (s *Service) UpdateProductCategory(ctx context.Context, id uuid.UUID, req *UpdateProductCategoryRequest) (*ProductCategory, error) {
	if err := s.requireSuperAdmin(ctx); err != nil {
		return nil, err
	}
	if req.IsEmpty() {
		return s.GetProductCategory(ctx, id)
	}

	var out *ProductCategory
	err := s.db.WithTx(ctx, func(ctx context.Context) error {
		current, err := s.repo.GetProductCategoryForUpdate(ctx, id)
		if err != nil {
			return mapReadErr(err, resProductCategory)
		}
		applyProductCategoryPatch(current, req)

		// parent_id == this row's own id is rejected as a business-rule
		// violation rather than being left to the CHECK, so the caller gets a
		// 422 with a usable message instead of a constraint error.
		if err := ValidateSelfReference("parent_id", current.ID, current.ParentID); err != nil {
			return ruleViolation(err)
		}
		if err := requireReference(ctx, current.ParentID, s.repo.GetProductCategory, resProductCategory); err != nil {
			return err
		}

		saved, err := s.repo.UpdateProductCategory(ctx, current)
		if err != nil {
			return mapWriteErr(err, resProductCategory)
		}
		out = saved
		return nil
	})
	if err != nil {
		return nil, err
	}
	return out, nil
}

// DeleteProductCategory soft-deletes a category.
//
// Both probes are required and they answer different questions. A category can be
// in use because a live medicine sits in it, or because it still has children —
// and the second case is the one a medicines probe can never see, because nothing
// points at the category directly. Removing a mid-tree category would otherwise
// silently promote its children to roots.
//
// This is the only resource with two probes: it is both referenced by medicines
// (category_id, RESTRICT) and self-referencing (contract §20, C-11).
func (s *Service) DeleteProductCategory(ctx context.Context, id uuid.UUID) error {
	if err := s.requireSuperAdmin(ctx); err != nil {
		return err
	}
	return s.db.WithTx(ctx, func(ctx context.Context) error {
		if _, err := s.repo.GetProductCategoryForUpdate(ctx, id); err != nil {
			return mapReadErr(err, resProductCategory)
		}
		err := checkUnreferenced(ctx, resProductCategory, id,
			s.repo.IsProductCategoryReferenced,
			s.repo.HasProductCategoryChildren,
		)
		if err != nil {
			return err
		}
		ok, err := s.repo.SoftDeleteProductCategory(ctx, id)
		if err != nil {
			return mapWriteErr(err, resProductCategory)
		}
		if !ok {
			return errs.NotFound(resProductCategory)
		}
		return nil
	})
}

// applyProductCategoryPatch copies the non-nil fields of the PATCH onto c.
//
// ParentID and Description are pointer columns: a SET pointer overwrites, including
// one addressing an empty string, while nil leaves the column untouched. Note the
// asymmetry the DTO forces — a pointer can express "set this" but not "set this to
// SQL NULL", so clearing a parent is done by re-parenting to a root, not by sending
// an explicit null.
func applyProductCategoryPatch(c *ProductCategory, req *UpdateProductCategoryRequest) {
	if req.Name != nil {
		c.Name = *req.Name
	}
	if req.ParentID != nil {
		c.ParentID = req.ParentID
	}
	if req.Description != nil {
		c.Description = req.Description
	}
	if req.SortOrder != nil {
		c.SortOrder = *req.SortOrder
	}
	if req.IsActive != nil {
		c.IsActive = *req.IsActive
	}
}
